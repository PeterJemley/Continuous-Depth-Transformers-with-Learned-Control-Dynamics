"""Exploratory comparison of N11's interrupted T4 runs with the A100 runs of the same seed and arm (deviation D1).

Written after N11's verdict, as D1 set out, and it decides nothing. The same code, seeds and arms ran on two kinds
of GPU, so each matched pair differs only by the hardware (and whatever the hardware changes in floating-point
order). For each measured quantity it reports the T4-minus-A100 difference over the matched pairs, against the
A100's own spread across seeds, which is the variation every claim so far has had to rise above.

    python n11_hardware.py [T4 results folder] [A100 results folder] [report path]
    # default: results/n11_t4, results/n11, N11_HARDWARE.md
"""
import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
T4 = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n11_t4'
A100 = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'results' / 'n11'
OUT = Path(sys.argv[3]) if len(sys.argv) > 3 else HERE / 'N11_HARDWARE.md'
SEEDS = [4001, 4002, 4003, 4004, 4005]
ARMS = ['clean', 'n80', 'n80-f8', 'n80-f32', 'n80-f128', 'n80-geom']

QUANTITIES = [  # (label, record, getter)
    ('Head A, validation loss', 'train', lambda r: r['final_loss_A']),
    ('Head B, validation loss (its own targets)', 'train', lambda r: r['final_loss_B']),
    ('Head B, validation loss (clean targets)', 'train', lambda r: r['final_loss_B_clean_targets']),
    ('Head A, clean loss, measurement windows', 'm', lambda r: r['functional']['A_clean']),
    ('Head B, clean loss, measurement windows', 'm', lambda r: r['functional']['B_clean']),
    ('Copy, clean loss, measurement windows', 'm', lambda r: r['functional']['copy_clean']),
    ('G, head B minus its own copy', 'm', lambda r: r['functional']['G']),
    ('Agreement ratio, head B vs its copy', 'm', lambda r: r['B_vs_copy']['agreement_ratio']),
    ('Payload-window KL', 'm', lambda r: r['payload_windows']['kl_B_to_copy']),
    ('Readout overlap, A and B', 'm', lambda r: r['readout_overlap_A_B']),
    ('Rotated control', 'm', lambda r: r['rotated_control']['agreement_ratio']),
]


def load(folder, kind, arm, seed):
    p = folder / (f'm_{arm}_seed{seed}.json' if kind == 'm' else f'{arm}_seed{seed}.json')
    return json.loads(p.read_text()) if p.exists() else None


def gap(folder, arm, seed):
    """head B's clean loss in this arm minus the same seed's n80 copy, on the same hardware's records."""
    m, y = load(folder, 'm', arm, seed), load(folder, 'm', 'n80', seed)
    return None if m is None or y is None else m['functional']['B_clean'] - y['functional']['copy_clean']


def main():
    pairs = [(a, s) for a in ARMS for s in SEEDS if load(T4, 'm', a, s) and load(T4, 'train', a, s)]
    if not pairs:
        raise SystemExit(f'No complete T4 records in {T4}.')
    env = {load(T4, 'train', a, s)['environment']['gpu'] for a, s in pairs}
    L = ['# N11: the T4 runs against the A100 runs, exploratory', '',
         'Generated by `n11_hardware.py`. Written after N11\'s verdict, as deviation D1 set out; it decides nothing. '
         f'T4 records: `{T4.name}/` (GPU: {", ".join(sorted(map(str, env)))}). A100 records: `{A100.name}/`.', '',
         f'**Matched pairs:** {len(pairs)}: ' + ', '.join(f'{a} {s}' for a, s in pairs) + '.', '',
         '## Differences, T4 minus A100, same seed and arm', '',
         'The last column is the A100\'s standard deviation across its five seeds, averaged over the arms in the matched pairs: '
         'the seed-to-seed variation the claims have had to rise above.', '',
         '| Quantity | Mean difference | Largest absolute difference | A100 seed-to-seed SD |', '|---|---|---|---|']
    for label, kind, get in QUANTITIES:
        d = [get(load(T4, kind, a, s)) - get(load(A100, kind, a, s)) for a, s in pairs]
        sds = [st.stdev([get(load(A100, kind, a, s)) for s in SEEDS]) for a in sorted({a for a, _ in pairs})]
        L.append(f'| {label} | {st.mean(d):+.4f} | {max(abs(x) for x in d):.4f} | {st.mean(sds):.4f} |')
    L += ['', '## The share of the gap closed, S, on each kind of GPU', '',
          'Only for seeds whose T4 records include `n80`, so that each kind of GPU supplies its own yardstick.', '',
          '| Arm | Seed | S, T4 | S, A100 | Difference |', '|---|---|---|---|---|']
    for a in ['n80-f8', 'n80-f32', 'n80-f128', 'n80-geom']:
        for s in SEEDS:
            g4, g4y, ga, gay = gap(T4, a, s), gap(T4, 'n80', s), gap(A100, a, s), gap(A100, 'n80', s)
            if None in (g4, g4y):
                continue
            s4, sa = 1 - g4 / g4y, 1 - ga / gay
            L.append(f'| {a} | {s} | {s4:+.3f} | {sa:+.3f} | {s4 - sa:+.3f} |')
    # Added after the T4 records were read (see the deviation log): N11b's steps, on each kind of GPU.
    L += ['', '## N11b\'s ordering on each kind of GPU (added after the T4 records were read)', '',
          'N11b required S(f8) < S(f32) < S(f128). The steps between strengths, to four decimals, for the seeds with a full T4 set.', '',
          '| Seed | GPU | S(f32) − S(f8) | S(f128) − S(f32) | Ordered |', '|---|---|---|---|---|']
    for s in SEEDS:
        if None in (gap(T4, 'n80', s), gap(T4, 'n80-f128', s)):
            continue
        for name, folder in (('T4', T4), ('A100', A100)):
            v = {a: 1 - gap(folder, a, s) / gap(folder, 'n80', s) for a in ('n80-f8', 'n80-f32', 'n80-f128')}
            L.append(f"| {s} | {name} | {v['n80-f32'] - v['n80-f8']:+.4f} | {v['n80-f128'] - v['n80-f32']:+.4f} | "
                     f"{'yes' if v['n80-f8'] < v['n80-f32'] < v['n80-f128'] else 'no'} |")
    L.append('')
    OUT.write_text('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
