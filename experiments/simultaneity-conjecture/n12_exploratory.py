"""Exploratory analysis of N12, written after the results were seen (see N12_NOTE.md). It decides nothing.

It gives, per seed and with 95% intervals, the differences the result note discusses: what each arm's training cost
or gave head A; how far each mixture-form head's inner softmax is from head A; how much the random targets cost
given a head that can represent them (sub20 minus n80-mix); how much the mixture head gained over a single
softmax fitted directly to the copy (n80-mix minus fit-single); and each head's agreement with its copy by seed.
Every number comes from the saved records.

    python n12_exploratory.py [results folder] [report path]   # default: results/n12 here, N12_EXPLORATORY.md
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n12'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N12_EXPLORATORY.md'
SEEDS = [4101, 4102, 4103, 4104, 4105]
ARMS = ['clean', 'n80', 'n80-mix', 'sub20']


def load(name):
    return json.loads((RES / f'{name}.json').read_text())


def ci(xs, digits=3):
    m, sd = st.mean(xs), st.stdev(xs)
    h = stats.t.ppf(0.975, len(xs) - 1) * sd / math.sqrt(len(xs))
    return f'{m:+.{digits}f} [{m - h:+.{digits}f}, {m + h:+.{digits}f}]'


def rng(xs, digits=3):
    return f'{min(xs):.{digits}f}–{max(xs):.{digits}f}'


def main():
    m = {(a, s): load(f'm_{a}_seed{s}') for a in ARMS for s in SEEDS}
    f = {(k, s): load(f'f_{k}_seed{s}') for k in ('single', 'mix') for s in SEEDS}
    fn = lambda a, s, k: m[(a, s)]['functional'][k]
    yard = lambda s: fn('n80', s, 'copy_clean')
    gap = lambda a, s: fn(a, s, 'B_clean') - yard(s)
    S = lambda a, s: 1 - gap(a, s) / gap('n80', s)
    S_fit = lambda k, s: 1 - (f[(k, s)]['functional']['B_clean'] - yard(s)) / gap('n80', s)
    L = ['# N12: exploratory analysis, written after the results', '',
         'Generated by `n12_exploratory.py` from the records in `results/n12/`. It was written after the results were seen and decides '
         'nothing (see `N12_NOTE.md`). Differences are paired by seed; intervals are 95% t-intervals over the five seeds.', '',
         '## What each arm\'s training did to head A', '',
         'Head A\'s loss on the clean targets of the measurement windows, minus the same seed\'s `clean` arm. Positive is worse.', '',
         '| Arm | Head A minus clean | By seed |', '|---|---|---|']
    for a in ARMS[1:]:
        d = [fn(a, s, 'A_clean') - fn('clean', s, 'A_clean') for s in SEEDS]
        L.append(f'| {a} | {ci(d)} | {", ".join(f"{x:+.3f}" for x in d)} |')
    L += ['', '## The inner reading against head A', '',
          'For the mixture-form heads, the inner softmax\'s loss on the clean targets minus head A\'s, and its agreement ratio with head A. '
          'For `n80`, head B is its own inner reading.', '',
          '| Arm | Inner softmax minus head A (nats) | Agreement with head A, by seed |', '|---|---|---|']
    for a in ('n80', 'n80-mix', 'sub20'):
        d = [fn(a, s, 'B_inner_clean') - fn(a, s, 'A_clean') for s in SEEDS]
        key = 'B_vs_A' if a == 'n80' else 'B_inner_vs_A'
        agree = [m[(a, s)][key]['agreement_ratio'] for s in SEEDS]
        L.append(f'| {a} | {ci(d)} | {", ".join(f"{x:.3f}" for x in agree)} |')
    L += ['', '## Differences in S, paired by seed', '', '| Difference | Value | What it measures |', '|---|---|---|',
          f'| S(sub20) − S(n80-mix) | {ci([S("sub20", s) - S("n80-mix", s) for s in SEEDS])} | the cost of the random targets, given a head that can represent them |',
          f'| S(n80-mix) − S(fit-single) | {ci([S("n80-mix", s) - S_fit("single", s) for s in SEEDS])} | what the mixture head gained over a single softmax fitted directly to the copy |',
          f'| S(sub20) − S(fit-single) | {ci([S("sub20", s) - S_fit("single", s) for s in SEEDS])} | the same, for the data-matched clean head |',
          f'| 1 − S(fit-single) | {ci([1 - S_fit("single", s) for s in SEEDS])} | the share of the gap no single-softmax readout of the n80 state reached |',
          '', '## Agreement with the ideal copy, by seed', '', '| Arm | Ratio by seed | Range |', '|---|---|---|']
    for a in ARMS[1:]:
        r = [m[(a, s)]['B_vs_copy']['agreement_ratio'] for s in SEEDS]
        L.append(f'| {a} | {", ".join(f"{x:.3f}" for x in r)} | {rng(r)} |')
    r = [f[('single', s)]['B_vs_copy']['agreement_ratio'] for s in SEEDS]
    L.append(f'| fit-single | {", ".join(f"{x:.3f}" for x in r)} | {rng(r)} |')
    L += ['', '## The fits', '', '| Fit | Final fit KL by seed | Relative change over the last 300 steps, by seed |', '|---|---|---|']
    for k in ('single', 'mix'):
        final = [f[(k, s)]['curve_every_50'][-1][1] for s in SEEDS]
        change = [f[(k, s)]['convergence']['relative_change'] for s in SEEDS]
        L.append(f'| fit-{k} | {", ".join(f"{x:.4f}" for x in final)} | {", ".join(f"{x:.4f}" for x in change)} |')
    L.append('')
    OUT.write_text('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
