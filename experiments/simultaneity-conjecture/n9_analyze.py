"""Apply N9's preregistered decision rules to the saved records and write N9_RESULTS.md.

Written and committed before any real N9 run. Every number in the report comes from the
JSON records in the results folder.

Precondition 2 (must match) is applied to every measured model, the S4 models included.

    python n9_analyze.py [results folder] [report path]   # default: results/n9 here, N9_RESULTS.md
"""
import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n9'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N9_RESULTS.md'

SEEDS = [3801, 3802, 3803, 3804, 3805]
OTHER = ('same', 'k4', 'k8')
NEEDED = 4
CONVERGED, SEPARATE = 0.85, 0.60
MATCH_MIN, STABLE_MIN = 0.999, 0.80
COPY = 'copy0.8'


def load(name):
    p = RES / f'{name}.json'
    return json.loads(p.read_text()) if p.exists() else None


def count_verdict(values, supported, refuted_word=''):
    n_hi = sum(v >= CONVERGED for v in values)
    n_lo = sum(v <= SEPARATE for v in values)
    if n_hi >= NEEDED:
        return f'**Supported: {supported}** Agreement ratio ≥ {CONVERGED} in {n_hi} of 5.', 'supported'
    if n_lo >= NEEDED:
        return f'**Refuted{refuted_word}.** Agreement ratio ≤ {SEPARATE} in {n_lo} of 5.', 'refuted'
    return f'**Intermediate.** Agreement ratio ≥ {CONVERGED} in {n_hi} and ≤ {SEPARATE} in {n_lo} of 5.', 'intermediate'


def main():
    summary = load('n9_summary') or {}
    c = summary.get('checks', {})
    rec = {(a, s): load(f'c_{a}_seed{s}') for a in ('noisy',) + OTHER for s in SEEDS}
    ss = [s for s in SEEDS if rec[('noisy', s)]]
    nz = {s: rec[('noisy', s)] for s in ss}
    others = [r for (a, s), r in rec.items() if a != 'noisy' and r]

    match_vals = [r['s1']['copy0']['agreement_ratio'] for r in nz.values()] + [r['s4']['copy0']['agreement_ratio'] for r in others]
    pre = {
        '1. The estimator works on mixtures: the analytic check, the identical-heads check, the windows and the unigram':
            bool(c.get('analytic', {}).get('pass')) and bool(c.get('identical_heads', {}).get('pass'))
            and bool(c.get('test_windows_shifted')) and abs(c.get('unigram', {}).get('sum', 0) - 1) < 1e-6,
        f'2. Must match: the copy at ρ = 0 has a ratio with head A of at least {MATCH_MIN}, in every measured model':
            bool(match_vals) and all(v >= MATCH_MIN for v in match_vals),
        f'3. Must differ: the rotated control\'s ratio ≤ {SEPARATE} in at least 4 of 5 noisy-arm models':
            sum(r['rotated_control']['agreement_ratio'] <= SEPARATE for r in nz.values()) >= NEEDED,
        '4. The right models are loaded: head A\'s overlap with the noisy head within 0.05 of N8\'s, in every model':
            bool(nz) and all(r['loading']['pass'] for r in nz.values()),
        f'5. Stable subspaces: head A, the noisy head and the copy at ρ = 0.8 each ≥ {STABLE_MIN}, in every model':
            bool(nz) and all(r['stability'][k] >= STABLE_MIN for r in nz.values() for k in ('A', 'B', COPY)),
    }
    pre_ok = all(pre.values())
    failed = '; '.join(k.split(':')[0] for k, ok in pre.items() if not ok)

    if len(ss) < 5:
        v9a = v9b = f'**Not reached: noisy-arm records for only {len(ss)} of 5 seeds.**'
        ka = kb = None
    elif not pre_ok:
        v9a = v9b = f'**Untestable: a precondition failed ({failed}).**'
        ka = kb = None
    else:
        v9a, ka = count_verdict([nz[s]['n9a']['agreement_ratio'] for s in ss], 'the measure recognises an ideal noisy copy.', ': it does not')
        v9b, kb = count_verdict([nz[s]['n9b']['agreement_ratio'] for s in ss], 'the trained noisy head is close to the ideal copy.')
    warn = []
    if ka == 'supported' and kb == 'supported':
        warn = ['', '**Warning: both claims came out supported, which the preregistration says should not happen, by the triangle inequality, '
                'given S3. Look for a bug before interpreting either verdict.**']

    L = ['# N9 results', '',
         'Generated by `n9_analyze.py` from the records in `results/n9/`. Preregistration: `N9_PREREGISTRATION.md`.',
         f"ρ = {summary.get('rho')}; readout rank {summary.get('readout_rank')}; subspaces of dimension {summary.get('subspace_rank')}, "
         f"measured on {summary.get('windows', {}).get('split')}-split windows {summary.get('windows', {}).get('measure')}; "
         f"shared uniforms from seed {summary.get('fisher_seed')}. All ratios are N8's target-free agreement ratio.", '',
         '## Verdicts', '',
         f'**N9a (primary: the measure recognises an ideal noisy copy):** {v9a}', '',
         f'**N9b (the trained noisy head is close to the ideal copy):** {v9b}'] + warn + ['',
         '## Preconditions', '', '| Precondition | Met |', '|---|---|']
    L += [f'| {k} | {"yes" if ok else "**no**"} |' for k, ok in pre.items()]
    an = c.get('analytic', {})
    if an:
        L.append(f"\nAnalytic check on mixtures (ρ = {an.get('rho')}, {an.get('positions')} positions, vocabulary {an.get('vocab')}, eigengap "
                 f"{an.get('eigengap_R_over_R+1', float('nan')):.2f}): sampled estimate's top-subspace overlap with the copy's exact Fisher "
                 f"{an['sampled']['top_subspace_overlap']:.4f} (relative error {an['sampled']['relative_error']:.3f}). For contrast, targets drawn "
                 f"from p instead of q: {an['targets_from_p']['top_subspace_overlap']:.4f} (error {an['targets_from_p']['relative_error']:.3f}); "
                 f"head A's own Fisher: {an['head_A_fisher']['top_subspace_overlap']:.4f} (error {an['head_A_fisher']['relative_error']:.3f}).")
    if c.get('identical_heads'):
        L.append(f"Identical-heads check: agreement ratio {c['identical_heads']['agreement_ratio']}.")
    if c.get('unigram'):
        L.append(f"Unigram: sums to {c['unigram']['sum']:.6f}; zero for {c['unigram']['zeros']} tokens; most frequent {c['unigram']['most_frequent_tokens']}.")

    L += ['', '## Noisy-arm models, by seed (agreement ratio; overlap in brackets)', '',
          '| Seed | Head A vs copy (N9a) | Noisy head vs copy (N9b) | Head A vs noisy head (S3) | N8\'s overlap, A vs noisy head | Copy at ρ = 0 | Rotated control |',
          '|---|---|---|---|---|---|---|']
    for s in ss:
        r = nz[s]
        rr = r['loading']['recorded_n8_overlap_A_B']
        L.append(f"| {s} | {r['n9a']['agreement_ratio']:.3f} ({r['n9a']['overlap_AB']:.3f}) | {r['n9b']['agreement_ratio']:.3f} ({r['n9b']['overlap_AB']:.3f}) | "
                 f"{r['s3']['agreement_ratio']:.3f} ({r['s3']['overlap_AB']:.3f}) | {'missing' if rr is None else f'{rr:.3f}'} | "
                 f"{r['s1']['copy0']['agreement_ratio']:.6f} | {r['rotated_control']['agreement_ratio']:.3f} |")

    L += ['', '## Secondary and exploratory measures', '', 'None of these enters a decision rule.', '',
          '### S1: head A against its copy, by noise rate (mean agreement ratio over seeds, with range)', '',
          '| ρ | Agreement ratio | Range |', '|---|---|---|']
    for k in (summary.get('rhos') or []):
        name = f'copy{k:g}'
        v = [nz[s]['s1'][name]['agreement_ratio'] for s in ss if name in nz[s]['s1']]
        if v:
            L.append(f'| {k:g} | {st.mean(v):.3f} | {min(v):.3f} – {max(v):.3f} |')
    if ss:
        s2 = [nz[s]['s2'] for s in ss]
        L += ['', '### S2: prediction space (means over seeds, per position)', '',
              '| Head | KL from the noisy head to it (nats) | Loss on clean targets | Loss on noisy targets |', '|---|---|---|---|']
        L.append(f"| Trained noisy head | 0 | {st.mean(x['loss_clean_targets']['B'] for x in s2):.3f} | {st.mean(x['loss_noisy_targets']['B'] for x in s2):.3f} |")
        for name in s2[0]['kl_noisy_head_to_copy']:
            L.append(f"| Copy of head A at ρ = {name[4:]} | {st.mean(x['kl_noisy_head_to_copy'][name] for x in s2):.3f} | "
                     f"{st.mean(x['loss_clean_targets'][name] for x in s2):.3f} | {st.mean(x['loss_noisy_targets'][name] for x in s2):.3f} |")
        L.append(f"\nThe noisy head puts {st.mean(x['noisy_head_mass_where_u_is_zero'] for x in s2):.2e} of its probability, on average, on the "
                 f"{s2[0]['tokens_where_u_is_zero']} tokens the training data never contains, where the copies at ρ > 0 put only head A's share.")
        L += ['', '### Stability of each head (means over seeds)', '', '| Head | Split-half stability |', '|---|---|']
        for k in nz[ss[0]]['stability']:
            L.append(f"| {k} | {st.mean(nz[s]['stability'][k] for s in ss):.3f} |")
    L += ['', '### S4: head A against its copy at ρ = 0.8 in N7\'s other models (agreement ratio, by seed)', '',
          '| Model | ' + ' | '.join(str(s) for s in SEEDS) + ' | Mean |', '|' + '---|' * (len(SEEDS) + 2)]
    for a in OTHER:
        v = [rec[(a, s)]['s4'][COPY]['agreement_ratio'] if rec[(a, s)] else None for s in SEEDS]
        have = [x for x in v if x is not None]
        L.append(f'| {a} | ' + ' | '.join('—' if x is None else f'{x:.3f}' for x in v) + f" | {st.mean(have):.3f} |" if have else f'| {a} | ' + ' | '.join('—' for _ in SEEDS) + ' | — |')
    L.append('')
    OUT.write_text('\n'.join(L))
    print('\n'.join(L[:12]))


if __name__ == '__main__':
    main()
