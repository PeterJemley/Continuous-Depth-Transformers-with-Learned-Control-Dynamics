"""Exploratory analysis of N10, written after the results were seen (see the deviation log). It decides nothing.

N10's functional gap G compares head B with the ideal noisy copy of the same model's head A. The payloads
changed head A, so they also moved that yardstick. This script compares head B's loss on the clean targets
against one fixed yardstick: the ideal copy built from the n80 model's head A of the same seed, on the same
windows. It also reports what each payload cost head A. Every number comes from the saved records.

    python n10_exploratory.py [results folder] [report path]   # default: results/n10 here, N10_EXPLORATORY.md
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n10'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N10_EXPLORATORY.md'
SEEDS = [3901, 3902, 3903, 3904, 3905]
PAYLOADS = ('n80-func', 'n80-geom', 'n80-data')


def load(name):
    return json.loads((RES / f'{name}.json').read_text())


def ci(xs):
    m, sd = st.mean(xs), st.stdev(xs)
    h = stats.t.ppf(0.975, len(xs) - 1) * sd / math.sqrt(len(xs))
    return f'{m:+.3f} [{m - h:+.3f}, {m + h:+.3f}]'


def main():
    f = {(a, s): load(f'm_{a}_seed{s}')['functional'] for a in ('n80',) + PAYLOADS for s in SEEDS}
    t = {(a, s): load(f'{a}_seed{s}') for a in ('n80',) + PAYLOADS for s in SEEDS}
    L = ['# N10: exploratory analysis, written after the results', '',
         'Generated by `n10_exploratory.py` from the records in `results/n10/`. This analysis was added after the results were seen, '
         'and decides nothing (see the deviation log in `N10_PREREGISTRATION.md`). Means over 5 seeds, with 95% intervals.', '',
         '## Head B against a fixed yardstick', '',
         'G_fixed = head B\'s loss on the clean targets minus that of the ideal copy built from the `n80` model\'s head A, same seed and windows. '
         'Lower is better; `n80` itself is the preregistered G.', '',
         '| Arm | G (preregistered) | G_fixed | Head B\'s improvement on clean targets vs n80 | Share of n80\'s gap closed |',
         '|---|---|---|---|---|']
    base = [f[('n80', s)]['B_clean'] - f[('n80', s)]['copy_clean'] for s in SEEDS]
    L.append(f"| n80 | {ci([f[('n80', s)]['G'] for s in SEEDS])} | {ci(base)} | — | — |")
    for a in PAYLOADS:
        gfix = [f[(a, s)]['B_clean'] - f[('n80', s)]['copy_clean'] for s in SEEDS]
        imp = [f[('n80', s)]['B_clean'] - f[(a, s)]['B_clean'] for s in SEEDS]
        share = [i / b for i, b in zip(imp, base)]
        L.append(f"| {a} | {ci([f[(a, s)]['G'] for s in SEEDS])} | {ci(gfix)} | {ci(imp)} | {ci(share)} |")
    L += ['', '## What each payload cost head A', '',
          '| Arm | Head A\'s loss on the measurement windows, minus n80\'s | Head A\'s validation loss, minus n80\'s |', '|---|---|---|']
    for a in PAYLOADS:
        L.append(f"| {a} | {ci([f[(a, s)]['A_clean'] - f[('n80', s)]['A_clean'] for s in SEEDS])} | "
                 f"{ci([t[(a, s)]['final_loss_A'] - t[('n80', s)]['final_loss_A'] for s in SEEDS])} |")
    L.append('')
    OUT.write_text('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
