"""Exploratory analysis of N11, written after the results were seen (see N11_NOTE.md). It decides nothing.

It asks why the functional payload failed its manipulation check (precondition 5f) while still closing part of
the gap: how far each arm's head B is from its own model's ideal copy on the payload windows, in absolute terms;
how the payload term moved during training; and how much of the payload's effect on its own windows carried over
to the measurement windows. Every number comes from the saved records.

    python n11_exploratory.py [results folder] [report path]   # default: results/n11 here, N11_EXPLORATORY.md
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n11'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N11_EXPLORATORY.md'
SEEDS = [4001, 4002, 4003, 4004, 4005]
ARMS = ['clean', 'n80', 'n80-f8', 'n80-f32', 'n80-f128', 'n80-geom']
FUNC = ['n80-f8', 'n80-f32', 'n80-f128']
CHECKPOINTS = [300, 900, 1500, 2100, 2850]


def load(name):
    return json.loads((RES / f'{name}.json').read_text())


def ci(xs, digits=3):
    m, sd = st.mean(xs), st.stdev(xs)
    h = stats.t.ppf(0.975, len(xs) - 1) * sd / math.sqrt(len(xs))
    return f'{m:.{digits}f} [{m - h:.{digits}f}, {m + h:.{digits}f}]'


def main():
    m = {(a, s): load(f'm_{a}_seed{s}') for a in ARMS for s in SEEDS}
    t = {(a, s): load(f'{a}_seed{s}') for a in ARMS for s in SEEDS}
    L = ['# N11: exploratory analysis, written after the results', '',
         'Generated by `n11_exploratory.py` from the records in `results/n11/`. It was written after the results were seen and '
         'decides nothing (see `N11_NOTE.md`). Means over 5 seeds, with 95% intervals.', '',
         '## Head B against its own model\'s ideal copy, on the 64 payload windows', '',
         'KL(head B ‖ copy), nats per position. In `clean` the copy is head A itself, so its value is how far apart two heads '
         'trained on the same targets are. Precondition 5f required `n80-f128` to be at most half of `n80`.', '',
         '| Arm | Payload-window KL | ÷ n80, same seed |', '|---|---|---|']
    for a in ARMS:
        kl = [m[(a, s)]['payload_windows']['kl_B_to_copy'] for s in SEEDS]
        rel = [k / m[('n80', s)]['payload_windows']['kl_B_to_copy'] for k, s in zip(kl, SEEDS)]
        L.append(f'| {a} | {ci(kl, 4)} | {ci(rel)} |')
    L += ['', '## The payload term during training', '',
          'The payload arms\' training-time payload term (KL on that step\'s 4 payload windows), averaged over the 50-step '
          'records nearest each checkpoint and over seeds. The unanchored arm does not compute it.', '',
          '| Arm | ' + ' | '.join(f'step {c}' for c in CHECKPOINTS) + ' |', '|---|' + '---|' * len(CHECKPOINTS)]
    for a in FUNC:
        row = []
        for c in CHECKPOINTS:
            vals = [v for s in SEEDS for step, v in t[(a, s)]['payload_term_every_50'] if abs(step - c) <= 100]
            row.append(f'{st.mean(vals):.4f}')
        L.append(f'| {a} | ' + ' | '.join(row) + ' |')
    L += ['', '## How much of the payload\'s effect carried over to new text', '',
          'S on the measurement windows divided by S on the payload windows, per seed. 1 means the effect on the payload\'s own '
          'windows carried over fully to text it never saw.', '',
          '| Arm | S, payload windows | S, measurement windows | Carry-over |', '|---|---|---|---|']
    for a in FUNC + ['n80-geom']:
        sp, sm = [], []
        for s in SEEDS:
            y = m[('n80', s)]
            gp = lambda r: r['payload_windows']['B_clean'] - y['payload_windows']['copy_clean']
            gm = lambda r: r['functional']['B_clean'] - y['functional']['copy_clean']
            sp.append(1 - gp(m[(a, s)]) / gp(y))
            sm.append(1 - gm(m[(a, s)]) / gm(y))
        L.append(f'| {a} | {ci(sp)} | {ci(sm)} | {ci([b / c for b, c in zip(sm, sp)])} |')
    L += ['', '## Run environment', '']
    envs = sorted({(r['environment']['gpu'], r['environment']['torch'], r['environment']['code_commit'][:7])
                   for r in list(m.values()) + list(t.values())})
    L += [f'- {g}, PyTorch {v}, code {c}' for g, v, c in envs]
    L.append(f"- Training time per run: {min(r['train_seconds'] for r in t.values()) / 60:.1f}–{max(r['train_seconds'] for r in t.values()) / 60:.1f} minutes; "
             f"resumes: {sum(r['resumes'] for r in t.values())}; skipped fp16 steps: {sum(r['skipped_steps_fp16'] for r in t.values())}")
    L.append('')
    OUT.write_text('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
