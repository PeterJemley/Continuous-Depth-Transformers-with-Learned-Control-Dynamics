"""Apply N6's preregistered decision rules to the saved records and write N6_RESULTS.md.

Written and committed before any real N6 run. Every number in the report comes from the
JSON records in the results folder.

    python n6_analyze.py [results folder] [report path]   # default: results/n6 here, N6_RESULTS.md
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n6'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N6_RESULTS.md'

SEEDS = [3601, 3602, 3603, 3604, 3605]
ARMS = ('same', 'k2', 'k4', 'k8')
NEEDED = 4
DROP, SD_SENSITIVE = 0.10, 0.05
SAME_MIN, STABLE_MIN = 0.95, 0.80
BAND = (0.40, 0.60)


def load(name):
    p = RES / f'{name}.json'
    return json.loads(p.read_text()) if p.exists() else None


def interval(xs, level=0.95):
    n = len(xs)
    m = st.mean(xs)
    sd = st.stdev(xs) if n > 1 else float('nan')
    half = stats.t.ppf(1 - (1 - level) / 2, n - 1) * sd / math.sqrt(n) if n > 1 else float('nan')
    return m, sd, m - half, m + half


def main():
    summary = load('n6_summary') or {}
    checks = summary.get('checks', {})
    trn = {(a, s): load(f'{a}_seed{s}') for a in ARMS for s in SEEDS}
    sub = {(a, s): load(f'sub_{a}_seed{s}') for a in ARMS for s in SEEDS}
    seeds = [s for s in SEEDS if all(trn[(a, s)] and sub[(a, s)] for a in ARMS)]

    def o(a, s):
        return sub[(a, s)]['overlap_AB']

    def stab(a, s):
        return min(sub[(a, s)]['stability_A_odd_even'], sub[(a, s)]['stability_B_odd_even'])

    same_data = bool(seeds) and all(len({trn[(a, s)].get('batch_fingerprint_step0') for a in ARMS}) == 1 for s in seeds)
    n_same = sum(o('same', s) >= SAME_MIN for s in seeds)
    stable = bool(seeds) and all(stab(a, s) >= STABLE_MIN for a in ('k2', 'k4', 'k8') for s in seeds)
    pre = {
        '1. Data and setup checks, and the same batches in all four arms of each seed':
            bool(checks.get('batch', {}).get('targets_are_i+1_to_i+8')) and all(x['pass'] for x in checks.get('same_model', [{'pass': False}]))
            and same_data,
        f'2. Must fail: the same arm\'s overlap ≥ {SAME_MIN} in at least 4 of 5': n_same >= NEEDED,
        f'3. Stable subspaces: every head\'s split-half stability ≥ {STABLE_MIN} in every k2, k4 and k8 model': stable,
    }
    pre_ok = all(pre.values())
    failed = '; '.join(k.split(':')[0] for k, ok in pre.items() if not ok)

    diffs = [o('k2', s) - o('k8', s) for s in seeds]
    prim = interval(diffs) if len(seeds) >= 2 else None
    if len(seeds) < 5:
        v6a = f'**Not reached: all four arms have records and measurements for only {len(seeds)} of 5 seeds.**'
    elif not pre_ok:
        v6a = f'**Untestable: a precondition failed ({failed}).**'
    else:
        m, sd, lo, hi = prim
        tail = f'o(2) − o(8) = {m:+.4f}, 95% interval [{lo:+.4f}, {hi:+.4f}], standard deviation {sd:.4f}.'
        if lo > DROP:
            v6a = f'**Supported: the balance point falls as the readings differ more.** {tail}'
        elif hi < DROP and sd <= SD_SENSITIVE:
            v6a = f'**Refuted.** {tail}' + (' The overlap *rose* with distance.' if hi < 0 else '')
        elif lo > 0 or hi < 0:
            v6a = f'**Some effect, size unclear.** {tail}'
        else:
            v6a = f'**Inconclusive.** {tail}'

    n_in = sum(BAND[0] <= o('k2', s) <= BAND[1] for s in seeds)
    n_out = len(seeds) - n_in
    if len(seeds) < 5:
        v6b = f'**Not reached: {len(seeds)} of 5 seeds.**'
    elif not pre_ok:
        v6b = f'**Untestable: a precondition failed ({failed}).**'
    elif n_in >= NEEDED:
        v6b = f'**Supported: the half-overlap replicates.** o(2) within {BAND[0]}–{BAND[1]} in {n_in} of 5.'
    elif n_out >= NEEDED:
        v6b = f'**Refuted.** o(2) outside {BAND[0]}–{BAND[1]} in {n_out} of 5.'
    else:
        v6b = f'**Intermediate.** o(2) within the band in {n_in} of 5.'

    L = ['# N6 results', '',
         'Generated by `n6_analyze.py` from the records in `results/n6/`. Preregistration: `N6_PREREGISTRATION.md`.',
         f"Readout rank {summary.get('readout_rank')}; subspaces of dimension {summary.get('subspace_rank')}, "
         f"measured on validation windows {summary.get('windows', {}).get('measure')}.", '',
         '## Verdicts', '', f'**N6a (primary: the balance point falls as the readings differ more):** {v6a}', '',
         f'**N6b (the half-overlap replicates):** {v6b}', '',
         '## Preconditions', '', '| Precondition | Met |', '|---|---|']
    L += [f'| {k} | {"yes" if ok else "**no**"} |' for k, ok in pre.items()]

    L += ['', '## The overlap of the two readings\' subspaces, by seed', '',
          'Head A predicts token i+1; head B predicts token i+k. o(k) is the mean squared cosine of the principal angles between their top subspaces at the ODE block\'s output.', '',
          '| Seed | o(1), same | o(2) | o(4) | o(8) | o(2) − o(8) | Ordered o(2) > o(4) > o(8)? |', '|---|---|---|---|---|---|---|']
    for s in seeds:
        ordered = o('k2', s) > o('k4', s) > o('k8', s)
        L.append(f"| {s} | {o('same', s):.3f} | {o('k2', s):.3f} | {o('k4', s):.3f} | {o('k8', s):.3f} | "
                 f"{o('k2', s) - o('k8', s):+.3f} | {'yes' if ordered else 'no'} |")
    if prim:
        L.append(f'\no(2) − o(8) (primary): mean {prim[0]:+.4f}, standard deviation {prim[1]:.4f}, 95% interval [{prim[2]:+.4f}, {prim[3]:+.4f}].')

    L += ['', '## Secondary and exploratory measures', '', 'None of these enters a decision rule.', '',
          '### S1: the whole ladder (means over seeds, 95% intervals)', '', '| Arm | k | Mean overlap | 95% interval |', '|---|---|---|---|']
    for a, k in zip(ARMS, (1, 2, 4, 8)):
        v = [o(a, s) for s in seeds]
        if len(v) >= 2:
            m, _, lo, hi = interval(v)
            L.append(f'| {a} | {k} | {m:.3f} | [{lo:.3f}, {hi:.3f}] |')
    L.append(f"\nSeeds with o(2) > o(4) > o(8): {sum(o('k2', s) > o('k4', s) > o('k8', s) for s in seeds)} of {len(seeds)}.")

    L += ['', '### S2: each head\'s loss (mean over seeds, whole validation split)', '', '| Arm | Head A (i+1) | Head B (i+k) |', '|---|---|---|']
    for a in ARMS:
        if seeds:
            L.append(f"| {a} | {st.mean(trn[(a, s)]['final_loss_A'] for s in seeds):.4f} | {st.mean(trn[(a, s)]['final_loss_B'] for s in seeds):.4f} |")

    L += ['', '### S3: split-half stability and stability-corrected overlap (means over seeds)', '',
          '| Arm | Stability A | Stability B | Overlap / √(stability A × stability B) |', '|---|---|---|---|']
    for a in ARMS:
        if seeds:
            sa = [sub[(a, s)]['stability_A_odd_even'] for s in seeds]
            sb = [sub[(a, s)]['stability_B_odd_even'] for s in seeds]
            corr = [o(a, s) / math.sqrt(sub[(a, s)]['stability_A_odd_even'] * sub[(a, s)]['stability_B_odd_even']) for s in seeds]
            L.append(f'| {a} | {st.mean(sa):.3f} | {st.mean(sb):.3f} | {st.mean(corr):.3f} |')

    unt = summary.get('untrained', {})
    if unt:
        L += ['', '### S4: change from initialisation (means over seeds)', '', '| Arm | Untrained overlap | Trained overlap | Change |', '|---|---|---|---|']
        for a in ARMS:
            u = [unt[f'seed{s}'][a]['overlap_AB'] for s in SEEDS if f'seed{s}' in unt]
            t = [o(a, s) for s in seeds]
            if u and t:
                L.append(f'| {a} | {st.mean(u):.3f} | {st.mean(t):.3f} | {st.mean(t) - st.mean(u):+.3f} |')
    L.append('')
    OUT.write_text('\n'.join(L))
    print('\n'.join(L[:12]))


if __name__ == '__main__':
    main()
