"""Apply N7's preregistered decision rules to the saved records and write N7_RESULTS.md.

Written and committed before any real N7 run. Every number in the report comes from the
JSON records in the results folder.

    python n7_analyze.py [results folder] [report path]   # default: results/n7 here, N7_RESULTS.md
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n7'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N7_RESULTS.md'

SEEDS = [3801, 3802, 3803, 3804, 3805]
ARMS = ('same', 'k4', 'k8', 'noisy')
NEEDED = 4
MARGIN, SD_SENSITIVE = 0.30, 0.05
SAME_MIN, STABLE_MIN = 0.95, 0.80
CONVERGED, SEPARATE = 0.85, 0.60


def load(name):
    p = RES / f'{name}.json'
    return json.loads(p.read_text()) if p.exists() else None


def interval(xs, level=0.95):
    n = len(xs)
    m = st.mean(xs)
    sd = st.stdev(xs) if n > 1 else float('nan')
    half = stats.t.ppf(1 - (1 - level) / 2, n - 1) * sd / math.sqrt(n) if n > 1 else float('nan')
    return m, sd, m - half, m + half


def main():
    summary = load('n7_summary') or {}
    c = summary.get('checks', {})
    trn = {(a, s): load(f'{a}_seed{s}') for a in ARMS for s in SEEDS}
    sub = {(a, s): load(f'sub_{a}_seed{s}') for a in ARMS for s in SEEDS}
    seeds = [s for s in SEEDS if all(trn[(a, s)] and sub[(a, s)] for a in ARMS)]

    def o(a, s):
        return sub[(a, s)]['overlap_AB']

    def ratio(a, s):
        return sub[(a, s)]['agreement_ratio']

    same_data = bool(seeds) and all(len({trn[(a, s)].get('batch_fingerprint_step0') for a in ARMS}) == 1 for s in seeds)
    stable = bool(seeds) and all(min(sub[(a, s)]['stability_A_odd_even'], sub[(a, s)]['stability_B_odd_even']) >= STABLE_MIN
                                 for a in ('k4', 'k8', 'noisy') for s in seeds)
    n_hard = sum(trn[('noisy', s)]['final_loss_B'] >= trn[('k4', s)]['final_loss_B'] for s in seeds)
    pre = {
        '1. Data and setup checks, the noise check, the identical-heads check, and the same batches in all four arms':
            bool(c.get('batch', {}).get('targets_are_i+1_to_i+8')) and bool(c.get('test_windows_shifted'))
            and bool(c.get('noise', {}).get('pass')) and bool(c.get('identical_heads', {}).get('pass'))
            and all(x['pass'] for x in c.get('same_model', [{'pass': False}])) and same_data,
        f'2. Must fail: the same arm\'s agreement ratio ≥ {SAME_MIN} in at least 4 of 5': sum(ratio('same', s) >= SAME_MIN for s in seeds) >= NEEDED,
        f'3. Stable subspaces: every head\'s split-half stability ≥ {STABLE_MIN} in every k4, k8 and noisy model': stable,
        '4. The noisy reading is hard: its loss at least the k4 head B\'s, in at least 4 of 5 seeds': n_hard >= NEEDED,
    }
    pre_ok = all(pre.values())
    failed = '; '.join(k.split(':')[0] for k, ok in pre.items() if not ok)

    diffs = [o('noisy', s) - o('k8', s) for s in seeds]
    prim = interval(diffs) if len(seeds) >= 2 else None
    if len(seeds) < 5:
        v7a = f'**Not reached: all four arms have records and measurements for only {len(seeds)} of 5 seeds.**'
    elif not pre_ok:
        v7a = f'**Untestable: a precondition failed ({failed}).**'
    else:
        m, sd, lo, hi = prim
        tail = f'o(noisy) − o(8) = {m:+.4f}, 95% interval [{lo:+.4f}, {hi:+.4f}], standard deviation {sd:.4f}.'
        if lo > MARGIN:
            v7a = f'**Supported: sharing tracks how different the readings are, not how hard.** {tail}'
        elif hi < MARGIN and sd <= SD_SENSITIVE:
            v7a = f'**Refuted.** {tail}'
        elif lo > 0 or hi < 0:
            v7a = f'**Some effect, size unclear.** {tail}'
        else:
            v7a = f'**Inconclusive.** {tail}'

    n_conv = sum(ratio('noisy', s) >= CONVERGED for s in seeds)
    n_sep = sum(ratio('noisy', s) <= SEPARATE for s in seeds)
    if len(seeds) < 5:
        v7b = f'**Not reached: {len(seeds)} of 5 seeds.**'
    elif not pre_ok:
        v7b = f'**Untestable: a precondition failed ({failed}).**'
    elif n_conv >= NEEDED:
        v7b = f'**Supported: a harder copy of the same reading converges.** Noisy head\'s agreement ratio ≥ {CONVERGED} in {n_conv} of 5.'
    elif n_sep >= NEEDED:
        v7b = f'**Refuted.** Noisy head\'s agreement ratio ≤ {SEPARATE} in {n_sep} of 5.'
    else:
        v7b = f'**Intermediate.** Agreement ratio ≥ {CONVERGED} in {n_conv} and ≤ {SEPARATE} in {n_sep} of 5.'

    L = ['# N7 results', '',
         'Generated by `n7_analyze.py` from the records in `results/n7/`. Preregistration: `N7_PREREGISTRATION.md`.',
         f"Noise rate {summary.get('noise_rate')}; readout rank {summary.get('readout_rank')}; subspaces of dimension "
         f"{summary.get('subspace_rank')}, measured on {summary.get('windows', {}).get('split')}-split windows "
         f"{summary.get('windows', {}).get('measure')}.", '',
         '## Verdicts', '', f'**N7a (primary: sharing tracks how different the readings are, not how hard):** {v7a}', '',
         f'**N7b (a harder copy of the same reading converges):** {v7b}', '',
         '## Preconditions', '', '| Precondition | Met |', '|---|---|']
    L += [f'| {k} | {"yes" if ok else "**no**"} |' for k, ok in pre.items()]
    nz = c.get('noise', {})
    if nz:
        L.append(f"\nNoise check: {nz.get('fraction_replaced', float('nan')):.3f} of one batch's targets replaced; "
                 f"most frequent replacement tokens {nz.get('most_frequent_tokens')}.")

    L += ['', '## Overlap and agreement ratio with the clean next-token head, by seed', '',
          '| Seed | same: overlap / ratio | k4 | k8 | noisy | o(noisy) − o(8) |', '|---|---|---|---|---|---|']
    for s in seeds:
        cells = [f"{o(a, s):.3f} / {ratio(a, s):.3f}" for a in ARMS]
        L.append(f'| {s} | ' + ' | '.join(cells) + f" | {o('noisy', s) - o('k8', s):+.3f} |")
    if prim:
        L.append(f'\no(noisy) − o(8) (primary): mean {prim[0]:+.4f}, standard deviation {prim[1]:.4f}, 95% interval [{prim[2]:+.4f}, {prim[3]:+.4f}].')

    L += ['', '## Secondary and exploratory measures', '', 'None of these enters a decision rule.', '',
          '### S1: means over seeds (95% intervals)', '', '| Arm | Overlap | Agreement ratio |', '|---|---|---|']
    for a in ARMS:
        if len(seeds) >= 2:
            mo, _, lo, hi = interval([o(a, s) for s in seeds])
            mr, _, rlo, rhi = interval([ratio(a, s) for s in seeds])
            L.append(f'| {a} | {mo:.3f} [{lo:.3f}, {hi:.3f}] | {mr:.3f} [{rlo:.3f}, {rhi:.3f}] |')
    L += ['', '### S2: losses (mean over seeds, whole validation split)', '',
          '| Arm | Head A (i+1) | Head B, own targets | Head B, clean targets |', '|---|---|---|---|']
    for a in ARMS:
        if seeds:
            L.append(f"| {a} | {st.mean(trn[(a, s)]['final_loss_A'] for s in seeds):.4f} | {st.mean(trn[(a, s)]['final_loss_B'] for s in seeds):.4f} | "
                     f"{st.mean(trn[(a, s)]['final_loss_B_clean_targets'] for s in seeds):.4f} |")
    L.append(f'\nSeeds in which the noisy head was at least as hard as k4: {n_hard} of {len(seeds)}.')
    L += ['', '### S3: split-half stability (means over seeds)', '', '| Arm | Stability A | Stability B |', '|---|---|---|']
    for a in ARMS:
        if seeds:
            L.append(f"| {a} | {st.mean(sub[(a, s)]['stability_A_odd_even'] for s in seeds):.3f} | {st.mean(sub[(a, s)]['stability_B_odd_even'] for s in seeds):.3f} |")
    unt = summary.get('untrained', {})
    if unt:
        L += ['', '### S4: change from initialisation (means over seeds)', '', '| Arm | Untrained overlap | Trained overlap | Change |', '|---|---|---|---|']
        for a in ARMS:
            u = [unt[f'seed{s}'][a]['overlap_AB'] for s in SEEDS if f'seed{s}' in unt]
            t = [o(a, s) for s in seeds]
            if u and t:
                L.append(f'| {a} | {st.mean(u):.3f} | {st.mean(t):.3f} | {st.mean(t) - st.mean(u):+.3f} |')
    n6r = HERE / 'results' / 'n6r'
    if n6r.is_dir() and seeds:
        L += ['', '### S5: k4 and k8 against N6r (mean overlap; different seeds and windows, descriptive only)', '',
              '| Arm | N6r | N7 |', '|---|---|---|']
        for a in ('k4', 'k8'):
            v = [json.loads((n6r / f'sub_{a}_seed{s}.json').read_text())['overlap_AB'] for s in range(3701, 3706) if (n6r / f'sub_{a}_seed{s}.json').exists()]
            if v:
                L.append(f'| {a} | {st.mean(v):.3f} | {st.mean(o(a, s) for s in seeds):.3f} |')
    L.append('')
    OUT.write_text('\n'.join(L))
    print('\n'.join(L[:12]))


if __name__ == '__main__':
    main()
