"""Exploratory analysis of N14, written after the results were seen (see N14_NOTE.md). It decides nothing.

It gives, per seed and with 95% intervals: the clean-target ladder's slopes and the clean-target loss at which it crosses
the 0.85 bar; the residuals against the ladder pooled over the four doses; the trace and the functional cost at each
dose against the random targets' share of the summed weight at the end of training; the control taken apart; and head A's
cost against the clean arm by arm. Every number comes from the saved records.

    python n14_exploratory.py [N14 results folder] [report path] [N12 records folder] [N13 records folder]
    # defaults: results/n14 here, N14_EXPLORATORY.md, results/n12, results/n13
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n14'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N14_EXPLORATORY.md'
N12 = Path(sys.argv[3]) if len(sys.argv) > 3 else HERE / 'results' / 'n12'
N13 = Path(sys.argv[4]) if len(sys.argv) > 4 else HERE / 'results' / 'n13'
SEEDS = [4101, 4102, 4103, 4104, 4105]
RUNG = ('sub20', 'sub10', 'sub05', 'sub025', 'sub0125')
DOSES = ('r10', 'r20', 'r40', 'n80-mix')
DOSE_OF = {'r10': 0.1, 'r20': 0.2, 'r40': 0.4, 'n80-mix': 0.8}
CONTROL = 'sub20-rw'
BAR = 0.85


def load(folder, name):
    return json.loads((folder / f'{name}.json').read_text())


def ci(xs, digits=3):
    m = st.mean(xs)
    h = stats.t.ppf(0.975, len(xs) - 1) * st.stdev(xs) / math.sqrt(len(xs)) if len(xs) > 1 else 0.0
    return f'{m:+.{digits}f} [{m - h:+.{digits}f}, {m + h:+.{digits}f}]'


def by_seed(xs, digits=3):
    return ', '.join(f'{x:+.{digits}f}' for x in xs)


def main():
    rec = {}
    for s in SEEDS:
        for a in ('sub20', 'n80-mix'):
            rec[(a, s)] = load(RES, f'r_{a}_seed{s}')
        for a in RUNG[1:] + DOSES[:-1] + (CONTROL,):
            rec[(a, s)] = load(RES, f'm_{a}_seed{s}')
    clean = {s: load(N12, f'm_clean_seed{s}') for s in SEEDS}
    trn = {(a, s): load(RES, f'{a}_seed{s}') for a in DOSES[:-1] for s in SEEDS}
    rep13 = {s: load(N13, f'n80-mix-rep_seed{s}') for s in SEEDS}     # bit-identical to n80-mix (N13): its discount record
    a_of = lambda a, s: (rec[(a, s)].get('B_inner_vs_A') or rec[(a, s)]['B_vs_A'])['agreement_ratio']
    dA = lambda a, s: rec[(a, s)]['functional']['B_inner_clean'] - rec[(a, s)]['functional']['A_clean']
    ladder = lambda s: sorted((dA(a, s), a_of(a, s)) for a in RUNG)

    def a_hat(s, x):
        pts = ladder(s)
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            if x0 <= x <= x1:
                return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
        return None

    def x_at(s, y):
        """The clean-target loss at which the seed's ladder crosses agreement y (first crossing from the top)."""
        pts = ladder(s)
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            if y1 <= y <= y0:
                return x0 + (x1 - x0) * (y0 - y) / (y0 - y1)
        return None

    L = ['# N14: exploratory analysis, written after the results', '',
         'Generated by `n14_exploratory.py` from the records in `results/n14/`, `results/n12/` and `results/n13/`. It was written after the results '
         'were seen and decides nothing (see `N14_NOTE.md`). Differences are paired by seed; intervals are 95% t-intervals over the five seeds.', '',
         '## The clean-target ladder: its slopes, and where it crosses the 0.85 bar', '',
         'Agreement with head A falls along the ladder as the clean-target loss rises. The slope of each segment, in agreement per nat, and '
         'the clean-target loss Δ_A at which the ladder crosses 0.85, the bar N10c and N12b fell just short of.', '',
         '| Seed | sub20 → sub10 | sub10 → sub05 | sub05 → sub025 | sub025 → sub0125 | Δ_A at a = 0.85 | Δ_A(n80-mix) |', '|---|---|---|---|---|---|---|']
    xs85 = []
    for s in SEEDS:
        pts = ladder(s)
        slopes = [(y1 - y0) / (x1 - x0) for (x0, y0), (x1, y1) in zip(pts, pts[1:])]
        x85 = x_at(s, BAR); xs85.append(x85)
        L.append(f'| {s} | ' + ' | '.join(f'{v:+.2f}' for v in slopes) + f' | {x85:.3f} | {dA("n80-mix", s):.3f} |')
    L += [f'', f'Δ_A at the bar: {ci(xs85)}; n80-mix\'s Δ_A: {ci([dA("n80-mix", s) for s in SEEDS])}; the difference: '
          f'{ci([dA("n80-mix", s) - x for s, x in zip(SEEDS, xs85)])}.', '']
    L += ['## The residuals against the ladder, by dose and pooled', '',
          'b = â − a: how far a model\'s agreement falls below a clean-target head\'s at the same clean-target loss. Positive is below the ladder.', '',
          '| Dose | b | By seed |', '|---|---|---|']
    pooled = []
    per = {}
    for a in DOSES:
        per[a] = [a_hat(s, dA(a, s)) - a_of(a, s) for s in SEEDS]
        L.append(f'| {a} ({DOSE_OF[a]}) | {ci(per[a])} | {by_seed(per[a])} |')
    pooled = [st.mean(per[a][i] for a in DOSES) for i in range(len(SEEDS))]
    L.append(f'| mean over the four doses | {ci(pooled)} | {by_seed(pooled)} |')
    L += ['', '## The trace and the functional cost at each dose, against the random targets\' share of the weight', '',
          'The share is the random targets\' part of the summed discount at the last recorded step (2,850); for n80-mix it comes from N13\'s '
          'bit-identical replicate, from the kept and replaced means at the batch\'s fractions. D(d) = a(sub20) − a(d); the functional cost is Δ_A(d) − Δ_A(sub20).', '',
          '| Dose | Share at the end | D(d) | Functional cost (nats) | D / share | Functional cost / share |', '|---|---|---|---|---|---|']
    for a in DOSES:
        if a == 'n80-mix':
            shares = []
            for s in SEEDS:
                e = rep13[s]['r_every_50'][-1]
                fr = rep13[s].get('noise_fraction_step0', 0.8)
                shares.append(fr * e[3] / (fr * e[3] + (1 - fr) * e[2]))
        else:
            shares = [trn[(a, s)]['r_every_50'][-1][3] for s in SEEDS]
        D = [a_of('sub20', s) - a_of(a, s) for s in SEEDS]
        F = [dA(a, s) - dA('sub20', s) for s in SEEDS]
        L.append(f'| {a} ({DOSE_OF[a]}) | {st.mean(shares):.2f} | {ci(D)} | {ci(F)} | {ci([d / sh for d, sh in zip(D, shares)], 2)} | '
                 f'{ci([f / sh for f, sh in zip(F, shares)], 2)} |')
    L += ['', '## The control taken apart', '',
          '`sub20-rw`: clean targets at the same positions as `sub20`, each weighted by the discount at ρ = 0.8, with no random targets.', '',
          '| Quantity | Value | By seed |', '|---|---|---|',
          f'| Δ_A | {ci([dA(CONTROL, s) for s in SEEDS])} | {by_seed([dA(CONTROL, s) for s in SEEDS])} |',
          f'| a, agreement with head A | {ci([a_of(CONTROL, s) for s in SEEDS])} | {by_seed([a_of(CONTROL, s) for s in SEEDS])} |',
          f'| â, the ladder at its Δ_A | {ci([a_hat(s, dA(CONTROL, s)) for s in SEEDS])} | {by_seed([a_hat(s, dA(CONTROL, s)) for s in SEEDS])} |',
          f'| b = â − a | {ci([a_hat(s, dA(CONTROL, s)) - a_of(CONTROL, s) for s in SEEDS])} | {by_seed([a_hat(s, dA(CONTROL, s)) - a_of(CONTROL, s) for s in SEEDS])} |',
          f'| a(sub20) − a(sub20-rw), the preregistered N14c quantity | {ci([a_of("sub20", s) - a_of(CONTROL, s) for s in SEEDS])} | '
          f'{by_seed([a_of("sub20", s) - a_of(CONTROL, s) for s in SEEDS])} |',
          f'| a(sub05) − a(sub20-rw): the rung it reads like | {ci([a_of("sub05", s) - a_of(CONTROL, s) for s in SEEDS])} | '
          f'{by_seed([a_of("sub05", s) - a_of(CONTROL, s) for s in SEEDS])} |',
          f'| Δ_A(sub0125) − Δ_A(sub20-rw): the rung it predicts like | {ci([dA("sub0125", s) - dA(CONTROL, s) for s in SEEDS])} | '
          f'{by_seed([dA("sub0125", s) - dA(CONTROL, s) for s in SEEDS])} |']
    L += ['', '## Head A against N12\'s clean arm, by arm', '',
          'Head A\'s loss on the clean targets, minus the same seed\'s `clean` arm, whose head B is trained on every clean target. Positive is worse.', '',
          '| Arm | Clean targets | Random targets | Head A minus clean | By seed |', '|---|---|---|---|---|']
    meta = {'sub20': (0.2, 0.0), 'r10': (0.2, 0.1), 'r20': (0.2, 0.2), 'r40': (0.2, 0.4), 'n80-mix': (0.2, 0.8),
            'sub10': (0.1, 0.0), 'sub05': (0.05, 0.0), 'sub025': (0.025, 0.0), 'sub0125': (0.0125, 0.0), 'sub20-rw': (0.2, 0.0)}
    for a, (fk, fd) in meta.items():
        x = [rec[(a, s)]['functional']['A_clean'] - clean[s]['functional']['A_clean'] for s in SEEDS]
        L.append(f'| {a} | {fk} | {fd} | {ci(x)} | {by_seed(x)} |')
    OUT.write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
