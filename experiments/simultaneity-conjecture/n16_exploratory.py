"""Exploratory analysis of N16, written after the results were seen (see N16_NOTE.md). It decides nothing.

It gives, per seed and with 95% intervals: the two-by-two of judge (head B's own discount, head A's judgement) against
random targets (absent, present), in clean-target loss and in agreement, with its main effects and interaction; the
oracle head against the oracle mask (the pattern the calibration entry recorded before the run); the neglect measurement
paired against sub20; the weights' course over training; and head A's cost. Every number comes from the saved records.

    python n16_exploratory.py [N16 results folder] [report path] [N13 records folder]
    # defaults: results/n16 here, N16_EXPLORATORY.md, results/n13
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n16'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N16_EXPLORATORY.md'
N13 = Path(sys.argv[3]) if len(sys.argv) > 3 else HERE / 'results' / 'n13'
SEEDS = [4101, 4102, 4103, 4104, 4105]
RUNG = ('clean', 'sub20', 'sub10', 'sub05', 'sub025', 'sub0125')
NEW = ('rw-oracle', 'sub20-oracle')
# the two-by-two: (judge, random targets) -> arm
CELL = {('B', 'absent'): 'sub20-rw', ('B', 'present'): 'rw-b1', ('A', 'absent'): 'sub20-oracle', ('A', 'present'): 'rw-oracle'}


def load(folder, name):
    return json.loads((folder / f'{name}.json').read_text())


def ci(xs, digits=3):
    m = st.mean(xs)
    h = stats.t.ppf(0.975, len(xs) - 1) * st.stdev(xs) / math.sqrt(len(xs)) if len(xs) > 1 else 0.0
    return f'{m:+.{digits}f} [{m - h:+.{digits}f}, {m + h:+.{digits}f}]'


def main():
    rec = {(a, s): load(RES, f'{"m" if a in NEW else "r"}_{a}_seed{s}') for a in NEW + ('rw-b1', 'sub20-rw') + RUNG for s in SEEDS}
    trn = {(a, s): load(RES, f'{a}_seed{s}') for a in NEW for s in SEEDS}
    b1 = {s: load(N13, f'n80-rw_seed{s}') for s in SEEDS}
    dA = lambda a, s: rec[(a, s)]['functional']['B_inner_clean'] - rec[(a, s)]['functional']['A_clean']
    ag = lambda a, s: (rec[(a, s)].get('B_inner_vs_A') or rec[(a, s)]['B_vs_A'])['agreement_ratio']
    ng = lambda a, s, k: rec[(a, s)]['neglect'][k]

    def a_hat(s, x):
        pts = sorted((dA(a, s), ag(a, s)) for a in RUNG)
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            if x0 <= x <= x1:
                return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
        return None

    def b(a, s):
        h = a_hat(s, dA(a, s))
        return None if h is None else h - ag(a, s)

    per = lambda f: ', '.join(f'{f(s):+.3f}' for s in SEEDS)
    L = ['# N16: exploratory analysis, written after the results', '',
         f'Generated by `n16_exploratory.py` from the records in `results/n16/` and `results/n13/`. It was written after the results were seen and decides nothing (see `N16_NOTE.md`). '
         'Differences are paired by seed; intervals are 95% t-intervals over the five seeds, not the preregistered 98.75%.', '']

    L += ['## The two-by-two: who judges, and whether random targets are present', '',
          'Four heads share the 20% clean targets at the same positions, each weighted by the discount at ρ = 0.8, and differ in two things: whose prediction the discount is computed from '
          '(head B\'s own, or head A\'s, detached), and whether the other 80% of positions carry random targets. All four divide the summed loss by all positions. '
          '`sub20`, the same clean targets at full weight with no random ones, is the reference. Δ_A is the inner reading\'s clean-target loss minus head A\'s.', '',
          '| Judge | Random targets absent | Random targets present | Effect of the random targets |', '|---|---|---|---|']
    for j, name in (('B', "head B's own (N14's `sub20-rw`, N13's `n80-rw`)"), ('A', "head A's (`sub20-oracle`, `rw-oracle`)")):
        L.append(f"| {name} | {ci([dA(CELL[(j, 'absent')], s) for s in SEEDS])} | {ci([dA(CELL[(j, 'present')], s) for s in SEEDS])} | "
                 f"{ci([dA(CELL[(j, 'present')], s) - dA(CELL[(j, 'absent')], s) for s in SEEDS])} |")
    L.append(f"| Effect of the judge (A − B) | {ci([dA('sub20-oracle', s) - dA('sub20-rw', s) for s in SEEDS])} | {ci([dA('rw-oracle', s) - dA('rw-b1', s) for s in SEEDS])} | "
             f"interaction {ci([(dA('rw-oracle', s) - dA('sub20-oracle', s)) - (dA('rw-b1', s) - dA('sub20-rw', s)) for s in SEEDS])} |")
    L += ['', f"`sub20` (no weighting, no random targets): {ci([dA('sub20', s) for s in SEEDS])}. Each cell against it, the weighting's cost: "
          + ', '.join(f"{CELL[k]} {ci([dA(CELL[k], s) - dA('sub20', s) for s in SEEDS])}" for k in CELL) + '.', '',
          '**The same in agreement with head A, a,** and the residual against the clean-target ladder at each head\'s own loss (b = â − a; positive is below the ladder):', '',
          '| Arm | a | b |', '|---|---|---|']
    for k in CELL:
        a = CELL[k]
        bs = [b(a, s) for s in SEEDS]
        L.append(f"| {a} | {ci([ag(a, s) for s in SEEDS])} | " + (ci(bs, 4) if all(x is not None for x in bs) else f"{sum(x is not None for x in bs)} of 5 bracketed") + ' |')
    L.append(f"| sub20 | {ci([ag('sub20', s) for s in SEEDS])} | on the ladder |")

    L += ['', '## The oracle head against the oracle mask', '',
          'The calibration entry recorded, before the real run, that `rw-oracle` sat at `sub20`\'s level in seed 3001 while `sub20-oracle` sat 0.16 above it. On the five seeds:', '',
          f"- Δ_A(rw-oracle) − Δ_A(sub20): {ci([dA('rw-oracle', s) - dA('sub20', s) for s in SEEDS])}; by seed {per(lambda s: dA('rw-oracle', s) - dA('sub20', s))}; "
          f"below zero in {sum(dA('rw-oracle', s) < dA('sub20', s) for s in SEEDS)} of 5.",
          f"- F − 1, the recovery beyond the shortfall: {ci([(dA('rw-b1', s) - dA('rw-oracle', s)) / (dA('rw-b1', s) - dA('sub20', s)) - 1 for s in SEEDS])}.",
          f"- Δ_A(sub20-oracle) − Δ_A(sub20) (S3): {ci([dA('sub20-oracle', s) - dA('sub20', s) for s in SEEDS])}; above zero in {sum(dA('sub20-oracle', s) > dA('sub20', s) for s in SEEDS)} of 5.",
          f"- a(rw-oracle) − a(sub20): {ci([ag('rw-oracle', s) - ag('sub20', s) for s in SEEDS])}.", '']

    L += ['## Neglect, paired against `sub20`', '',
          'The fraction of clean targets on the measurement windows whose weight under a head\'s own discount is below 0.01, and the inner reading\'s loss on that set and on the rest. '
          'Every head ignores some targets: the hardest ones, on which even the clean head\'s loss is about 12 nats.', '',
          '| Arm | Ignored by own discount | Minus sub20\'s | Loss on own-ignored | Loss on the rest | Ignored by head A |', '|---|---|---|---|---|---|']
    for a in ('rw-b1', 'rw-oracle', 'sub20-oracle', 'sub20-rw', 'clean', 'sub20', 'sub0125'):
        L.append(f"| {a} | {ci([ng(a, s, 'own_ignored_fraction') for s in SEEDS], 4)} | {ci([ng(a, s, 'own_ignored_fraction') - ng('sub20', s, 'own_ignored_fraction') for s in SEEDS], 4)} | "
                 f"{ci([ng(a, s, 'loss_on_own_ignored') for s in SEEDS], 2)} | {ci([ng(a, s, 'loss_on_rest_own') for s in SEEDS], 2)} | {ci([ng(a, s, 'A_ignored_fraction') for s in SEEDS], 4)} |")

    def b1_at(s, x):
        e = min(b1[s]['r_every_50'], key=lambda e: abs(e[0] - x))
        f = b1[s].get('noise_fraction_step0', 0.8)
        return e[2], e[3], f * e[3] / (f * e[3] + (1 - f) * e[2])

    L += ['', '## The weights over training', '',
          'Mean weight on the kept positions (clean targets) and on the replaced ones (random targets), and their ratio, at the recorded step nearest each listed step; '
          '`rw-b1` from N13\'s records. The ratio is how strongly each judge tells clean targets from random ones.', '',
          '| Step | rw-b1 kept / replaced / ratio | rw-oracle kept / replaced / ratio | sub20-oracle kept | rw-oracle kept − rw-b1 kept |', '|---|---|---|---|---|']
    for x in (0, 50, 100, 200, 300, 600, 1500, 2850):
        bk = [b1_at(s, x) for s in SEEDS]
        ok = [min(trn[('rw-oracle', s)]['w_every_50'], key=lambda e: abs(e[0] - x)) for s in SEEDS]
        sk = [min(trn[('sub20-oracle', s)]['w_every_50'], key=lambda e: abs(e[0] - x)) for s in SEEDS]
        L.append(f"| {x} | {st.mean(e[0] for e in bk):.3f} / {st.mean(e[1] for e in bk):.3f} / {st.mean(e[0] / e[1] for e in bk):.2f} | "
                 f"{st.mean(e[2] for e in ok):.3f} / {st.mean(e[3] for e in ok):.3f} / {st.mean(e[2] / e[3] for e in ok):.2f} | {st.mean(e[2] for e in sk):.3f} | "
                 f"{ci([o[2] - k[0] for o, k in zip(ok, bk)])} |")

    L += ['', '## Head A\'s cost', '',
          'Head A\'s clean-target loss against the same seed\'s `clean` arm and against `rw-b1`: '
          + ', '.join(f"{a} {ci([rec[(a, s)]['functional']['A_clean'] - rec[('clean', s)]['functional']['A_clean'] for s in SEEDS], 4)}" for a in ('rw-b1', 'rw-oracle', 'sub20-oracle', 'sub20-rw', 'sub20'))
          + '; against rw-b1: ' + ', '.join(f"{a} {ci([rec[(a, s)]['functional']['A_clean'] - rec[('rw-b1', s)]['functional']['A_clean'] for s in SEEDS], 4)}" for a in NEW) + '.', '']
    OUT.write_text('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
