"""Exploratory analysis of N13, written after the results were seen (see N13_NOTE.md). It decides nothing.

It gives, per seed and with 95% intervals, the differences the result note discusses: D taken apart into what the
constant discount did to head A and to head B's own reading; what each arm's training did to head A against N12's
clean arm; the identity's differences by seed, with the per-position divergences; and the discount's means at the
end of training and averaged over the schedule, against the constant 0.2. Every number comes from the saved records.

    python n13_exploratory.py [N13 results folder] [report path] [N12 records folder]
    # defaults: results/n13 here, N13_EXPLORATORY.md, results/n12
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 'n13'
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'N13_EXPLORATORY.md'
N12 = Path(sys.argv[3]) if len(sys.argv) > 3 else HERE / 'results' / 'n12'
SEEDS = [4101, 4102, 4103, 4104, 4105]
NEW = ['n80-rw', 'n80-mix-rep', 'n80-w02']
OLD = ['n80', 'n80-mix', 'sub20']


def load(folder, name):
    return json.loads((folder / f'{name}.json').read_text())


def ci(xs, digits=3):
    m = st.mean(xs)
    h = stats.t.ppf(0.975, len(xs) - 1) * st.stdev(xs) / math.sqrt(len(xs)) if len(xs) > 1 else 0.0
    return f'{m:+.{digits}f} [{m - h:+.{digits}f}, {m + h:+.{digits}f}]'


def by_seed(xs, digits=3):
    return ', '.join(f'{x:+.{digits}f}' for x in xs)


def main():
    m = {(a, s): load(RES, f'r_{a}_seed{s}') for a in OLD for s in SEEDS}
    m.update({(a, s): load(RES, f'm_{a}_seed{s}') for a in NEW for s in SEEDS})
    tr = {(a, s): load(RES, f'{a}_seed{s}') for a in NEW for s in SEEDS}
    clean = {s: load(N12, f'm_clean_seed{s}') for s in SEEDS}
    fn = lambda a, s, k: m[(a, s)]['functional'][k]
    yard = lambda s: fn('n80', s, 'copy_clean')
    S = lambda a, s: 1 - (fn(a, s, 'B_clean') - yard(s)) / (fn('n80', s, 'B_clean') - yard(s))
    dA = lambda a, s: fn(a, s, 'B_inner_clean') - fn(a, s, 'A_clean')
    agree = lambda a, s: (m[(a, s)].get('B_inner_vs_A') or m[(a, s)]['B_vs_A'])['agreement_ratio']

    L = ['# N13: exploratory analysis, written after the results', '',
         'Generated by `n13_exploratory.py` from the records in `results/n13/` and `results/n12/`. It was written after the results '
         'were seen and decides nothing (see `N13_NOTE.md`). Differences are paired by seed; intervals are 95% t-intervals over the five seeds.', '',
         '## D taken apart: what the constant discount did to each head', '',
         'Within a seed, `n80-w02` against N12\'s `n80`: head A\'s loss on the clean targets, head B\'s own softmax\'s loss on the clean '
         'targets, and their difference, which is D. Negative is better.', '',
         '| Quantity | Difference, w02 minus n80 | By seed |', '|---|---|---|']
    a_ch = [fn('n80-w02', s, 'A_clean') - fn('n80', s, 'A_clean') for s in SEEDS]
    b_ch = [fn('n80-w02', s, 'B_inner_clean') - fn('n80', s, 'B_inner_clean') for s in SEEDS]
    d = [b - a for a, b in zip(a_ch, b_ch)]
    L += [f'| Head A, clean targets | {ci(a_ch)} | {by_seed(a_ch)} |',
          f'| Head B\'s own softmax, clean targets | {ci(b_ch)} | {by_seed(b_ch)} |',
          f'| D = the second minus the first | {ci(d)} | {by_seed(d)} |']
    L += ['', '## What each arm\'s training did to head A', '',
          'Head A\'s loss on the clean targets, minus the same seed\'s N12 `clean` arm. Positive is worse. N12\'s arms are re-measured here; '
          'their values equal N12\'s.', '',
          '| Arm | Head A minus clean | By seed |', '|---|---|---|']
    for a in OLD + NEW:
        x = [fn(a, s, 'A_clean') - clean[s]['functional']['A_clean'] for s in SEEDS]
        L.append(f'| {a} | {ci(x)} | {by_seed(x)} |')
    L += ['', '## The identity by seed: `n80-rw` against `n80-mix`', '',
          'Aggregate differences (new minus old), then the per-position symmetrised KL on the measurement windows.', '',
          '| Quantity | Difference | By seed |', '|---|---|---|']
    rows = [('Δ_A, the inner reading minus head A', [dA('n80-rw', s) - dA('n80-mix', s) for s in SEEDS]),
            ('S, in the mixture form', [S('n80-rw', s) - S('n80-mix', s) for s in SEEDS]),
            ('Agreement of the inner softmax with head A', [agree('n80-rw', s) - agree('n80-mix', s) for s in SEEDS]),
            ('Head A, clean targets', [fn('n80-rw', s, 'A_clean') - fn('n80-mix', s, 'A_clean') for s in SEEDS]),
            ('Head B, clean targets, mixture form', [fn('n80-rw', s, 'B_clean') - fn('n80-mix', s, 'B_clean') for s in SEEDS])]
    for name, x in rows:
        L.append(f'| {name} | {ci(x, 4)} | {by_seed(x, 4)} |')
    for key, name in (('inner_symmetrised', 'inner softmax'), ('mix_symmetrised', 'mixture form'), ('A_symmetrised', 'head A')):
        x = [m[('n80-rw', s)]['partner'][key] for s in SEEDS]
        L.append(f'| Per-position KL, {name} | {ci(x, 4)} | {by_seed(x, 4)} |')
    rep = [max(abs(dA('n80-mix-rep', s) - dA('n80-mix', s)), m[('n80-mix-rep', s)]['partner']['inner_symmetrised'],
               m[('n80-mix-rep', s)]['partner']['A_symmetrised']) for s in SEEDS]
    L += ['', f'The replicate, `n80-mix-rep` against `n80-mix`: the largest of its Δ_A difference and its per-position KLs, by seed: {by_seed(rep, 6)}.',
          '', 'For comparison, `n80-w02` against `n80`, two trainings with different losses:', '',
          '| Per-position KL | Mean | By seed |', '|---|---|---|']
    for key, name in (('inner_symmetrised', 'inner softmax'), ('mix_symmetrised', 'mixture form'), ('A_symmetrised', 'head A')):
        x = [m[('n80-w02', s)]['partner'][key] for s in SEEDS]
        L.append(f'| {name} | {ci(x, 4)} | {by_seed(x, 4)} |')
    L += ['', '## The discount, at the end and over the schedule', '',
          'From each run\'s record of r(y) every 50 steps: the batch mean, and the means on kept and on replaced positions. In `n80-rw` the '
          'discount is in use; in the others it is computed from their logits and recorded only. The last record is at step 2,850 of 2,879. '
          'The constant in `n80-w02` is 0.2.', '',
          '| Arm | Batch mean, averaged over the schedule | Batch mean at the end | Kept at the end | Replaced at the end | Kept / replaced at the end |',
          '|---|---|---|---|---|---|']
    for a in NEW:
        recs = {s: tr[(a, s)]['r_every_50'] for s in SEEDS}
        avg = [st.mean(r[1] for r in recs[s]) for s in SEEDS]
        end = [recs[s][-1] for s in SEEDS]
        ratio = [e[2] / e[3] for e in end]
        L.append(f'| {a} | {ci(avg)} | {ci([e[1] for e in end])} | {ci([e[2] for e in end])} | {ci([e[3] for e in end])} | '
                 f'{st.mean(ratio):.1f} ({min(ratio):.1f}–{max(ratio):.1f}) |')
    recs = {s: tr[('n80-rw', s)]['r_every_50'] for s in SEEDS}
    steps = [0, 50, 100, 200, 300, 500, 1000, 1500, 2000, 2500, 2850]
    L += ['', 'In `n80-rw`, the kept and replaced means along the schedule (means over seeds):', '',
          '| Step | ' + ' | '.join(str(x) for x in steps) + ' |', '|---|' + '---|' * len(steps)]
    for j, name in ((2, 'kept'), (3, 'replaced')):
        vals = []
        for x in steps:
            vals.append(st.mean(min(recs[s], key=lambda r: abs(r[0] - x))[j] for s in SEEDS))
        L.append(f'| {name} | ' + ' | '.join(f'{v:.3f}' for v in vals) + ' |')
    L += ['', '## Preconditions 2 and 5, and N13b, in numbers', '',
          'What the preregistered report summarises as yes or no, by seed: the largest difference between N13\'s re-measurement of each N12 '
          'model and N12\'s record (losses, then ratios); gap(`n80`), head B\'s clean-target loss minus the copy\'s; and how much worse '
          '`n80`\'s softmax does on clean targets when placed in the mixture form, which is N13b\'s gap(`n80`, mixture readout) minus gap(`n80`).', '',
          '| Seed | Reproduction, largest loss difference | Reproduction, largest ratio difference | gap(n80) | Mixture form minus n80 |', '|---|---|---|---|---|']
    for s in SEEDS:
        reps = [m[(a, s)]['reproduction'] for a in OLD if m[(a, s)].get('reproduction')]
        mixform = load(RES, f'r_n80-mixform_seed{s}')['functional']['B_clean']
        L.append(f'| {s} | {max(r["max_loss_difference"] for r in reps):.1e} | {max(r["max_ratio_difference"] for r in reps):.1e} | '
                 f'{fn("n80", s, "B_clean") - yard(s):.3f} | {mixform - fn("n80", s, "B_clean"):+.3f} |')
    OUT.write_text('\n'.join(L) + '\n')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
