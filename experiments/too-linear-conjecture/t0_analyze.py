"""Apply T0's preregistered decision rule to t0_results.json and write T0_RESULTS.md.

Written and committed before any real T0 result existed. Every number in the report
comes from t0_results.json.

    python t0_analyze.py [path to t0_results.json]    # default: results/t0_results.json here
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 't0_results.json'
OUT = HERE / 'T0_RESULTS.md'

# The vector the decision rule is applied to. 'field' is the ODE block's vector-field
# parameters without alpha, per the 2026-10-04 amendment in T0_PREREGISTRATION.md;
# 'ode' would be every ODE block parameter, as in the plan before the amendment.
PRIMARY_KEY = 'field'
SUPPORT_MAX, SUPPORT_GAP = 0.90, 0.05
REFUTE_MIN, REFUTE_GAP = 0.98, 0.01
MODERATE_GAP = 0.01
REF_MIN = 0.95


def f(x, d=4):
    return 'n/a' if x is None else (f'{x:.{d}f}' if isinstance(x, float) else str(x))


def main():
    r = json.loads(SRC.read_text())
    seeds = [str(s) for s in r['config']['seeds']]
    n = len(seeds)
    need = n - 1  # 5 of 6
    pk, rk = ('field_cos', 'field_reference_cos') if PRIMARY_KEY == 'field' else ('primary_cos', 'reference_cos')
    lines = ['# Results: T0, are Model A\'s training gradients the gradients of its own forward pass?', '',
             'Generated by `t0_analyze.py` from `results/t0_results.json`. Every number below comes from that file.',
             f'Primary vector: `{PRIMARY_KEY}`. Models: {n}. Draws per gradient type: {r.get("k_used", "n/a")}.', '']

    # ---------------------------------------------------------------- controls
    c = r['controls']
    checks = {
        'weights: recomputed test losses match the records': all(v['pass'] for v in r['weight_check'].values()),
        'must-match 1, repeatability': c['pass']['mm1'],
        'must-match 2, same forward pass': c['pass']['mm2'],
        'must-match 3, exact gradient equals a hand-written Euler loop': c['pass']['mm3'],
        f'must-match 4, agreement for a time-independent field at alpha 0.001 ({PRIMARY_KEY})': r['mm4_pass'][PRIMARY_KEY],
        f'must-fail, random sign flips ({PRIMARY_KEY})': c['pass'][f'mf1_{PRIMARY_KEY}'],
        f'injected effect, equal-norm noise ({PRIMARY_KEY})': c['pass'][f'injected_{PRIMARY_KEY}'],
    }
    controls_ok = all(checks.values())
    has_primary = 'primary' in r
    precondition = has_primary and r['precondition_met'][PRIMARY_KEY]

    # ---------------------------------------------------------------- verdict
    if not controls_ok:
        verdict, basis = 'untestable', 'a control failed: ' + ', '.join(k for k, v in checks.items() if not v)
    elif not has_primary:
        verdict, basis = 'untestable', 'the primary measurement did not run'
    elif not precondition:
        verdict, basis = 'too noisy to decide', f'noise reference below {REF_MIN} in some model at {r["k_used"]} draws'
    else:
        p = {s: r['primary'][s][pk] for s in seeds}
        ref = {s: r['primary'][s][rk] for s in seeds}
        sup = [s for s in seeds if p[s] < SUPPORT_MAX and p[s] < ref[s] - SUPPORT_GAP]
        refu = [s for s in seeds if p[s] >= min(REFUTE_MIN, ref[s] - REFUTE_GAP)]
        mod = [s for s in seeds if p[s] < ref[s] - MODERATE_GAP]
        if len(sup) >= need:
            verdict = 'supported: material defect'
        elif len(refu) >= need:
            verdict = 'refuted: no material defect'
        elif len(mod) >= need:
            verdict = 'intermediate: a measurable but moderate defect'
        else:
            verdict = 'intermediate: mixed'
        basis = (f'models meeting the support condition: {len(sup)} of {n}; the refutation condition: {len(refu)} of {n}; '
                 f'cosine below its reference by more than {MODERATE_GAP}: {len(mod)} of {n}')
    lines += ['## Verdict', '', f'**{verdict}.** {basis}.', '', '## Controls', '', '| Check | Passed |', '|---|---|']
    lines += [f'| {k} | {"yes" if v else "NO"} |' for k, v in checks.items()]
    lines += ['', f"Values: repeatability {f(c['mm1_repeatability_cos'], 7)}; loss difference {c['mm2_loss_rel_diff']:.2e}; "
              f"downstream gradient {f(c['mm2_downstream_cos'], 7)}; exact against loop {f(c['mm3_exact_vs_loop_cos'], 7)}; "
              f"sign flip {f(c[f'mf1_sign_flip_cos_{PRIMARY_KEY}'])}; equal-norm noise {f(c[f'inj_equal_norm_noise_cos_{PRIMARY_KEY}'])} "
              "(expected 0.7071).", '',
              f"For comparison, the sign-flip control on every ODE parameter including alpha: {f(c['mf1_sign_flip_cos_ode'])}.", '']

    if has_primary:
        lines += ['## Primary outcome', '',
                  'Cosine between the mean training gradient and the mean exact gradient for the same forward passes, '
                  'averaged over batches, against the noise reference: two independent means of exact gradients.', '',
                  '| Seed | Learned α | Primary cosine | Noise reference | Gap | Norm ratio, training / exact |', '|---|---|---|---|---|---|']
        for s in seeds:
            v = r['primary'][s]
            nr = v['norm_ratio_field'] if PRIMARY_KEY == 'field' else v['norm_ratio_ode']
            lines.append(f"| {s} | {f(r['alpha_learned'][s], 3)} | {f(v[pk])} | {f(v[rk])} | {f(v[rk] - v[pk])} | {f(nr, 3)} |")
        vals = [r['primary'][s][pk] for s in seeds]
        if n > 1:
            m, sd = st.mean(vals), st.stdev(vals)
            lines += ['', f'Mean primary cosine {m:.4f}, standard deviation {sd:.4f} across models '
                      f'(about {math.degrees(math.acos(max(-1, min(1, m)))):.1f}° between the mean gradients).', '']

        lines += ['## Secondary outcomes', '', '### S1, a single training step', '',
                  '| Seed | Training against exact, same masks | Exact against exact, different masks | Ratio of errors |', '|---|---|---|---|']
        for s in seeds:
            v = r['primary'][s]
            a, b = (v['single_cos_a_c_field'], v['single_cos_c_c2_field']) if PRIMARY_KEY == 'field' else (v['single_cos_a_c'], v['single_cos_c_c2'])
            ratio = (1 - a) / (1 - b) if b < 1 else None
            lines.append(f'| {s} | {f(a)} | {f(b)} | {f(ratio, 2)} |')
        mults = list(r['s3'][seeds[0]].keys())
        lines += ['', '### S2 and S3, dropout off, as α is scaled', '',
                  'Multiples of each model\'s learned α. S2 is the column at 1.', '',
                  '| Seed | ' + ' | '.join(f'α × {m}' for m in mults) + ' |', '|---|' + '---|' * len(mults)]
        for s in seeds:
            lines.append(f'| {s} | ' + ' | '.join(f(r['s3'][s][m][f'cos_{PRIMARY_KEY}']) for m in mults) + ' |')
        lines += ['', '### S4, freshly initialised models (α = 0.1)', '', '| Seed | Primary cosine | Noise reference |', '|---|---|---|']
        for s in seeds:
            v = r['s4'][s]
            lines.append(f'| {s} | {f(v[pk])} | {f(v[rk])} |')
        lines += ['', '### S6, upstream parameters (embeddings and early blocks)', '', '| Seed | Cosine | Noise reference |', '|---|---|---|']
        for s in seeds:
            v = r['primary'][s]
            lines.append(f"| {s} | {f(v['upstream_cos'])} | {f(v['upstream_reference_cos'])} |")
        lines += ['', '### S7, training gradient under fp16 autocast, exploratory', '']
        if isinstance(r['s7'], dict):
            lines += ['| Seed | Cosine with the fp32 exact mean |', '|---|---|'] + [f"| {s} | {f(r['s7'][s][PRIMARY_KEY])} |" for s in seeds]
        else:
            lines.append(str(r['s7']))
        lines += ['', '### S8, the gradient of α itself', '', '| Seed | Training mean | Exact mean | Exact, second mean |', '|---|---|---|---|']
        for s in seeds:
            b = r['primary'][s]['batches']
            mean = lambda k: st.mean(x[k] for x in b)  # noqa: E731
            lines.append(f"| {s} | {mean('alpha_grad_mean_a'):.3e} | {mean('alpha_grad_mean_c'):.3e} | {mean('alpha_grad_mean_c2'):.3e} |")
        lines += ['', '### S9, the time-mismatch floor: dropout off, α = 0.001, time embedding intact', '', '| Seed | Cosine |', '|---|---|']
        lines += [f"| {s} | {f(r['s9_time_floor'][s][f'cos_{PRIMARY_KEY}'], 6)} |" for s in seeds]
        lines += ['', 'Must-match 4, for comparison (time embedding switched off): '
                  + ', '.join(f"{s}: {f(r['mm4'][s][f'cos_{PRIMARY_KEY}'], 6)}" for s in seeds) + '.', '']

    env = r['environment']
    lines += ['## Provenance', '', f"Code commit `{str(env.get('code_commit'))[:7]}`, PyTorch {env.get('torch')}, "
              f"torchdiffeq {r['torchdiffeq']['version']}, device {env.get('gpu') or env.get('device')}, "
              f"test mode {env.get('test_mode')}. Run time {r.get('seconds', 0) / 60:.1f} min.", '',
              'Weight check, recomputed test loss against the record: '
              + ', '.join(f"{k[-4:]}: {v['recomputed']:.6f} / {v['recorded']:.6f}" for k, v in r['weight_check'].items()) + '.', '']
    OUT.write_text('\n'.join(lines))
    print('\n'.join(lines[:12]))


if __name__ == '__main__':
    main()
