"""Apply T1's preregistered decision rules to the run records and write T1_RESULTS.md.

Written and committed before any real T1 run. Every number in the report comes from the
JSON records in the results folder.

    python t1_analyze.py [results folder]    # default: results/t1 here
"""
import json
import math
import statistics as st
import sys
from pathlib import Path

from scipy import stats

HERE = Path(__file__).resolve().parent
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results' / 't1'
OUT = HERE / 'T1_RESULTS.md'

MARGIN = 0.05
FAMILY_ALPHA = 0.05
N_CONTRASTS = 4
SD_SENSITIVE = 0.04
# (name, first arm, second arm, what it tests); each difference is second minus first.
CONTRASTS = [('G', 'AX', 'AA', 'does the adjoint gradient cost loss? (primary)'),
             ('P', 'B6', 'B5', 'does losing one block cost about as much as Model A loses?'),
             ('C2', 'B6', 'T4', 'does weight-tied depth with a standard block match the baseline?'),
             ('F', 'T4', 'AX', 'does the ODE form cost loss beyond weight tying?')]
EXPLORATORY = [('B5 to T4', 'B5', 'T4'), ('B6 to AA, the whole gap', 'B6', 'AA')]


def load(name):
    p = RES / f'{name}.json'
    return json.loads(p.read_text()) if p.exists() else None


def interval(diffs, level):
    n = len(diffs)
    m = st.mean(diffs)
    sd = st.stdev(diffs) if n > 1 else float('nan')
    half = stats.t.ppf(1 - (1 - level) / 2, n - 1) * sd / math.sqrt(n) if n > 1 else float('nan')
    return m, sd, m - half, m + half


def classify(lo, hi, sd):
    if hi < -MARGIN:
        return 'material: the second arm is better'
    if lo > MARGIN:
        return 'material: the second arm is worse'
    if -MARGIN <= lo and hi <= MARGIN:
        return 'negligible' if sd <= SD_SENSITIVE else 'inconclusive (spread too large to call negligible)'
    if lo > 0 or hi < 0:
        return 'some effect, size unclear'
    return 'inconclusive'


def f(x, d=4):
    return 'n/a' if x is None or (isinstance(x, float) and math.isnan(x)) else (f'{x:+.{d}f}' if isinstance(x, float) else str(x))


def main():
    summary = load('t1_summary') or {}
    seeds = sorted({int(p.stem.rsplit('seed', 1)[1]) for p in RES.glob('main_B6_seed*.json')})
    arms = ['B6', 'B5', 'T4', 'AX', 'AA']
    val = {(a, s): (load(f'main_{a}_seed{s}') or {}).get('final_val_loss') for a in arms for s in seeds}
    complete = [s for s in seeds if all(val[(a, s)] is not None for a in arms)]
    level = 1 - FAMILY_ALPHA / N_CONTRASTS
    lines = ['# Results: T1, where does Model A\'s loss gap come from?', '',
             'Generated by `t1_analyze.py` from the run records. Every number below comes from those files.', '',
             f'Seeds with all five arms finished: {len(complete)} ({", ".join(map(str, complete)) or "none"}). '
             f'Intervals for the four contrasts are Bonferroni-corrected, {100 * level:.2f}%; the margin is ±{MARGIN} nats.', '']

    # ---------------------------------------------------------------- controls
    c = summary.get('checks', {})
    con = c.get('construction', {})
    same = c.get('same_model', [])
    null = [(s, (load(f'null_B6_seed{s}') or {}).get('final_val_loss')) for s in complete]
    null_d = [n - val[('B6', s)] for s, n in null if n is not None]
    short = [(s, (load(f'short_B6_seed{s}') or {}).get('final_val_loss')) for s in complete]
    short_d = [x - val[('B6', s)] for s, x in short if x is not None]
    null_ok = short_ok = None
    if len(null_d) >= 2:
        m, sd, lo, hi = interval(null_d, level)
        null_ok = classify(lo, hi, sd) == 'negligible'
        null_txt = f'mean {f(m)}, interval [{f(lo)}, {f(hi)}], sd {sd:.4f}: {"negligible, passed" if null_ok else "NOT negligible, failed"}'
    else:
        null_txt = 'not enough runs'
    if len(short_d) >= 2:
        m, sd, lo, hi = interval(short_d, level)
        short_ok = lo > 0
        short_txt = f'mean {f(m)}, interval [{f(lo)}, {f(hi)}]: {"detected, passed" if short_ok else "NOT detected, failed"}'
    else:
        short_txt = 'not enough runs'
    lines += ['## Controls', '',
              f"- Construction: {'passed' if con.get('pass') else 'FAILED'}; parameters {con.get('params')}.",
              f"- Same model, two backward passes: {'passed' if same and all(x['pass'] for x in same) else 'FAILED'} in "
              f"{sum(x['pass'] for x in same)} of {len(same)} seeds; largest loss difference "
              f"{max((x['loss_rel_diff'] for x in same), default=float('nan')):.2e}, smallest downstream cosine "
              f"{min((x['downstream_cos'] for x in same), default=float('nan')):.7f}.",
              f'- Null contrast, B6 with another initialisation minus B6: {null_txt}.',
              f'- Injected effect, B6 at 80% of the budget minus B6: {short_txt}.', '']
    reliable = bool(con.get('pass')) and same and all(x['pass'] for x in same) and null_ok and short_ok
    if not reliable:
        lines += ['**At least one control failed or is missing, so the contrasts below are reported as inconclusive, '
                  'as preregistered, whatever their intervals show.**', '']

    # ---------------------------------------------------------------- confirmatory contrasts
    lines += ['## Confirmatory contrasts', '', '| Contrast | Tests | Mean | 98.75% interval | SD | Outcome |', '|---|---|---|---|---|---|']
    results = {}
    for name, a, b, what in CONTRASTS:
        diffs = [val[(b, s)] - val[(a, s)] for s in complete]
        if len(diffs) < 2:
            lines.append(f'| {name}: {b} − {a} | {what} | n/a | n/a | n/a | not enough seeds |')
            continue
        m, sd, lo, hi = interval(diffs, level)
        outcome = classify(lo, hi, sd) if reliable else 'inconclusive (a control failed)'
        results[name] = (m, lo, hi, outcome)
        lines.append(f'| {name}: {b} − {a} | {what} | {f(m)} | [{f(lo)}, {f(hi)}] | {sd:.4f} | {outcome} |')
    gap = [val[('AA', s)] - val[('B6', s)] for s in complete]
    if 'P' in results and len(gap) >= 2:
        half_gap = st.mean(gap) / 2
        _, lo, hi, _ = results['P']
        p_out = ('supported' if lo >= half_gap else 'refuted' if hi < half_gap else 'inconclusive') if reliable else 'inconclusive (a control failed)'
        lines += ['', f'Rival P\'s extra rule: half the whole gap AA − B6 is {half_gap:.4f}. '
                  f'B5 − B6 interval [{f(lo)}, {f(hi)}]: rival P {p_out}.']

    # ---------------------------------------------------------------- per seed and exploratory
    lines += ['', '## Validation loss by seed', '', '| Seed | ' + ' | '.join(arms) + ' |', '|---|' + '---|' * len(arms)]
    for s in seeds:
        lines.append(f'| {s} | ' + ' | '.join('n/a' if val[(a, s)] is None else f'{val[(a, s)]:.4f}' for a in arms) + ' |')
    lines += ['', '## Exploratory contrasts (unadjusted 95% intervals)', '', '| Contrast | Mean | 95% interval |', '|---|---|---|']
    for label, a, b in EXPLORATORY:
        diffs = [val[(b, s)] - val[(a, s)] for s in complete]
        if len(diffs) >= 2:
            m, sd, lo, hi = interval(diffs, 0.95)
            lines.append(f'| {label}: {b} − {a} | {f(m)} | [{f(lo)}, {f(hi)}] |')
    lines += ['', '## Learning rates', '', f"Chosen: {summary.get('learning_rates')}.",
              f"New sweeps (validation loss by rate): {summary.get('sweeps')}.",
              f"Stage 1 sweeps reused for B6 and AA: {summary.get('stage1_sweeps')}.", '',
              '## α during training (AX and AA)', '', '| Seed | AX final α | AA final α |', '|---|---|---|']
    for s in seeds:
        ax, aa = load(f'main_AX_seed{s}') or {}, load(f'main_AA_seed{s}') or {}
        lines.append(f"| {s} | {f(ax.get('alpha_final'), 3)} | {f(aa.get('alpha_final'), 3)} |")
    lines += ['', '## Training time per run (hours)', '', '| Arm | Mean |', '|---|---|']
    for a in arms:
        t = [(load(f'main_{a}_seed{s}') or {}).get('train_seconds') for s in seeds]
        t = [x for x in t if x is not None]
        lines.append(f'| {a} | {st.mean(t) / 3600:.3f} |' if t else f'| {a} | n/a |')
    lines.append('')
    OUT.write_text('\n'.join(lines))
    print('\n'.join(lines[:30]))


if __name__ == '__main__':
    main()
